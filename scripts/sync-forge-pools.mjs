#!/usr/bin/env node
// Collect the Mystic Forge recipes that take "any of a pool" of ingredients,
// once, into packages/recipes/src/forge-pools-data.ts, so nothing looks them
// up at run time. The wiki lists which items are eligible; the yields are the
// ones its page text states, curated below. Only add a family whose average
// yield the wiki states. Re-run when the game changes (needs `pnpm build`
// first):
//
//   node scripts/sync-forge-pools.mjs
import { writeFileSync } from 'node:fs';
import { WikiClient } from '../packages/wiki/dist/index.js';

/**
 * `fixed` items plus `stacks` stacks of `stack` pool items each, all of one
 * item within a stack. `output` is the average per forge.
 */
const FAMILIES = [
  {
    // Amalgamated Gemstone. Wiki: one per forge with "a rare chance of more"
    // (no average stated, so 1); bulk gives 10 with about a 10% chance of 25,
    // 11.5 on average.
    output: 68063,
    /** What the eligible items are called. */
    label: 'crests, orbs or doubloons',
    forms: [
      { fixed: [[24277, 1]], stacks: 3, stack: 3, yields: 1, output: 1 },
      { fixed: [[19721, 5]], stacks: 3, stack: 25, yields: 10, output: 11.5 },
    ],
    /** Fewer eligible items than this means the query went wrong. */
    least: 20,
  },
];

const wiki = new WikiClient();
const rows = [];
for (const family of FAMILIES) {
  const recipes = await wiki.mysticForgeRecipes([family.output]);
  for (const form of family.forms) {
    const fixed = JSON.stringify(form.fixed);
    const pool = new Set();
    let source;
    for (const r of recipes) {
      if (r.output_item_count !== form.yields) continue;
      const rest = r.ingredients.filter((i) => !form.fixed.some(([id, count]) => i.item_id === id && i.count === count));
      if (rest.length !== form.stacks || r.ingredients.length !== form.stacks + form.fixed.length) continue;
      if (rest.some((i) => i.item_id === undefined || i.count !== form.stack)) continue;
      for (const i of rest) pool.add(i.item_id);
      source ??= { name: r.name, url: r.url };
    }
    if (pool.size < family.least) throw new Error(`only ${pool.size} eligible items for ${family.output} ${fixed}`);
    rows.push({
      output: family.output,
      count: form.output,
      fixed: form.fixed,
      stacks: form.stacks,
      stack: form.stack,
      label: family.label,
      items: [...pool].sort((a, b) => a - b),
      wiki: source,
    });
  }
}

writeFileSync(
  new URL('../packages/recipes/src/forge-pools-data.ts', import.meta.url),
  `// Generated by scripts/sync-forge-pools.mjs; do not edit.
// Source: wiki.guildwars2.com recipe data (eligible items), and the yields its
// pages state (curated in the script).

export const FORGE_POOLS_AS_OF = '${new Date().toISOString().slice(0, 10)}';

/**
 * Mystic Forge recipes taking \`fixed\` items and \`stacks\` stacks of \`stack\`
 * units, each stack of any one of \`items\`. \`count\` is the average yield.
 */
export const FORGE_POOLS: readonly {
  output: number;
  count: number;
  fixed: readonly (readonly [id: number, count: number])[];
  stacks: number;
  stack: number;
  label: string;
  items: readonly number[];
  wiki: { name: string; url: string };
}[] = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(rows.map((r) => `${r.output} yield ${r.count}: ${r.items.length} eligible items`).join('\n'));
