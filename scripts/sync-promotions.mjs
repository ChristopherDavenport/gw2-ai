#!/usr/bin/env node
// Collect Mystic Forge material promotions from the wiki, once, into
// packages/core/src/promotions-data.ts, so nothing looks them up at run time.
// Re-run when the game changes them (needs `pnpm build` first):
//
//   node scripts/sync-promotions.mjs
import { writeFileSync } from 'node:fs';
import { Gw2Client } from '../packages/client/dist/index.js';
import { materialPromotion } from '../packages/recipes/dist/index.js';
import { WikiClient } from '../packages/wiki/dist/index.js';

/** Philosopher's Stone and Mystic Crystal, sold for Spirit Shards. */
const STONES = [20796, 20799];

const gw2 = new Gw2Client();
const wiki = new WikiClient();

const materials = (await gw2.all('/v2/materials')).flatMap((category) => category.items);
const promotions = [];
for (const recipe of await wiki.mysticForgeRecipes(materials)) {
  const promotion = materialPromotion(recipe);
  if (!promotion) continue;
  promotions.push({
    output: recipe.output_item_id,
    net: promotion.output_count,
    inputs: promotion.ingredients.map((i) => [i.id, i.count]).sort((a, b) => a[0] - b[0]),
  });
}

const stonesPerShard = {};
const pages = await wiki.itemPages(STONES);
for (const [id, title] of pages) {
  const offer = (await wiki.vendorOffers(title)).find(
    (o) => !o.historical && o.costs.length === 1 && o.costs[0].name === 'Spirit Shard',
  );
  if (!offer) throw new Error(`no Spirit Shard offer for ${title}`);
  stonesPerShard[id] = offer.quantity / offer.costs[0].amount;
}

const unique = new Map(promotions.map((p) => [JSON.stringify(p), p]));
const rows = [...unique.values()].sort((a, b) => a.output - b.output || a.inputs[0][0] - b.inputs[0][0]);
if (rows.length < 50) throw new Error(`only ${rows.length} promotions found; the wiki query may have failed`);

writeFileSync(
  new URL('../packages/core/src/promotions-data.ts', import.meta.url),
  `// Generated by scripts/sync-promotions.mjs; do not edit.
// Source: wiki.guildwars2.com recipe data, and the averages on its
// Mystic Forge/Material Promotion page.

export const PROMOTIONS_AS_OF = '${new Date().toISOString().slice(0, 10)}';

/** \`net\`: average units gained per forge; the one \`output\` each forge takes is already left out. */
export const PROMOTIONS: readonly { output: number; net: number; inputs: readonly (readonly [id: number, count: number])[] }[] = [
${rows.map((r) => `  ${JSON.stringify(r).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\w)/g, ', ')},`).join('\n')}
];

/** Stones sold per Spirit Shard, by item id. */
export const STONES_PER_SHARD: Readonly<Record<number, number>> = ${JSON.stringify(stonesPerShard)};
`,
);
console.log(`${rows.length} promotions, stones per shard ${JSON.stringify(stonesPerShard)}`);
